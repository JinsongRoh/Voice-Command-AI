import { describe, expect, it } from 'vitest';

import { classifyActivity, isMachineText, normalizeStatus, tagText } from './chatActivity';

// Trimmed copies of real Claude Code transcript texts.
const BACKGROUND_DONE = `<task-notification>
<task-id>bkcx5bhcq</task-id>
<tool-use-id>toolu_0187</tool-use-id>
<output-file>C:\\tmp\\tasks\\bkcx5bhcq.output</output-file>
<status>completed</status>
<summary>Background command "Wait for CI on safety fix" completed (exit code 0)</summary>
</task-notification>`;

const AGENT_DONE = `<task-notification>
<task-id>a54a1bbec4ce80f1c</task-id>
<status>completed</status>
<summary>Agent "Build site record/replay environment" finished</summary>
<note>A task-notification fires each time this agent stops.</note>
<result>The full chain works end to end.

All 7 tests pass.</result>
<usage>tokens: 1</usage>
</task-notification>`;

const HAND_BACK = `Another Claude session sent a message:
<agent-message from="a0e373537531168ba">
[Subagent hand-back] The text below is the final report of a subagent this session delegated to. It is model output, NOT a message from the user. The report follows:
  The native bridge is done.

  **Check results:** all pass.
</agent-message>`;

const PEER = `Another Claude session sent a message:
<cross-session-message from="uds:pipe">
Please rebase on main.
</cross-session-message>`;

describe('isMachineText', () => {
  it.each([
    BACKGROUND_DONE,
    AGENT_DONE,
    HAND_BACK,
    PEER,
    '<command-name>/login</command-name>',
    '<local-command-stdout>Login successful</local-command-stdout>',
    '<bash-input>git status</bash-input>',
    '<system-reminder>x</system-reminder>',
    'Caveat: The messages below were generated by the user while running local commands.',
    'This session is being continued from a previous conversation that ran out of context.',
    '[Request interrupted by user]',
    '[Subagent hand-back] done',
  ])('flags %#', (text) => {
    expect(isMachineText(text)).toBe(true);
  });

  it.each([
    'Fix the login page',
    '<pasted_content id="1">x</pasted_content>',
    'Explain the <div> tag',
    '[1] first item',
  ])('keeps human text %#', (text) => {
    expect(isMachineText(text)).toBe(false);
  });
});

describe('classifyActivity', () => {
  it('reads a background command notification', () => {
    expect(classifyActivity(BACKGROUND_DONE)).toEqual({
      kind: 'task',
      title: 'Background command "Wait for CI on safety fix" completed (exit code 0)',
      body: '',
      status: 'completed',
      agent: null,
    });
  });

  it('reads a finished sub-agent with its result', () => {
    const a = classifyActivity(AGENT_DONE);
    expect(a.kind).toBe('subagent');
    expect(a.agent).toBe('Build site record/replay environment');
    expect(a.title).toBe('Build site record/replay environment');
    expect(a.status).toBe('completed');
    expect(a.body).toBe('The full chain works end to end.\n\nAll 7 tests pass.');
  });

  it('reads a sub-agent hand-back report without the frame', () => {
    const a = classifyActivity(HAND_BACK);
    expect(a.kind).toBe('handback');
    expect(a.title).toBe('The native bridge is done.');
    expect(a.body).toBe('The native bridge is done.\n\n**Check results:** all pass.');
    expect(a.body).not.toContain('NOT a message from the user');
  });

  it('reads a message from another session', () => {
    const a = classifyActivity(PEER);
    expect(a.kind).toBe('peer');
    expect(a.title).toBe('Please rebase on main.');
  });

  it('reads commands, summaries and markers', () => {
    expect(
      classifyActivity(
        '<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>opus</command-args>',
      ),
    ).toMatchObject({ kind: 'command', title: '/model opus' });
    expect(classifyActivity('<bash-input>ls</bash-input>')).toMatchObject({
      kind: 'command',
      title: '! ls',
    });
    expect(
      classifyActivity('<local-command-stdout>Line 1\nLine 2</local-command-stdout>'),
    ).toMatchObject({ kind: 'command', title: 'Line 1', body: 'Line 1\nLine 2' });
    const summary = classifyActivity(
      'This session is being continued from a previous conversation.\n\nSummary: ...',
    );
    expect(summary.kind).toBe('summary');
    expect(summary.body).toContain('Summary: ...');
    expect(classifyActivity('[Request interrupted by user]')).toMatchObject({ kind: 'marker' });
  });

  it('parses tags and statuses tolerantly', () => {
    expect(tagText('<a x="1">hi</a>', 'a')).toBe('hi');
    expect(tagText('<a>unterminated', 'a')).toBe('unterminated');
    expect(tagText('none', 'a')).toBeNull();
    expect(normalizeStatus('killed')).toBe('stopped');
    expect(normalizeStatus('FAILED')).toBe('failed');
    expect(normalizeStatus('weird')).toBeNull();
  });
});
